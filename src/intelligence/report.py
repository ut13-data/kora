"""
knowledge_report.md: a readable summary of what KORA discovered about Nexora.

Generated from the same outputs as the JSON files, so the report can never
disagree with the data behind it. Re-run src.build_intelligence and it updates.
"""

from collections import Counter


def _table(headers: list[str], rows: list[list]) -> str:
    def cell(v) -> str:
        return str(v).replace("|", "/").replace("\n", " ")
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join(cell(v) for v in row) + " |" for row in rows]
    return "\n".join(lines)


def _cut(text: str, n: int = 140) -> str:
    text = " ".join(str(text).split())
    return text if len(text) <= n else text[: n - 1] + "…"


def build_report(result, summary, validation: dict, answers: list[dict]) -> str:
    e = result.entities
    out: list[str] = []
    add = out.append

    add("# KORA Knowledge Report: Nexora Systems")
    add(f"\nGenerated by Phase 3 (Knowledge Intelligence). Joining stages computed as of **{summary.as_of}**. "
        "Every number below comes from `data/intelligence/*.json`; every claim there carries its source.\n")

    # ---- overview ----
    add("## At a glance\n")
    counts = summary.entities_by_type
    add(_table(["What", "Count"], [
        ["Documents", counts.get("document", 0)], ["Departments", counts.get("department", 0)],
        ["Roles", counts.get("role", 0)], ["Employees", counts.get("employee", 0)],
        ["Processes (incl. archived)", counts.get("process", 0)], ["Products", counts.get("product", 0)],
        ["Customers named", counts.get("customer", 0)], ["Topics", counts.get("topic", 0)],
        ["Relationships", summary.relationships], ["Approval / escalation rules",
                                                   f"{summary.rules_by_type.get('approval', 0)} / {summary.rules_by_type.get('escalation', 0)}"],
        ["Conflicts", sum(summary.conflicts_by_type.values())], ["Corroborations (cross-checks passed)", summary.corroborations],
        ["Knowledge gaps (high / medium / low)",
         " / ".join(str(summary.gaps_by_severity.get(s, 0)) for s in ("high", "medium", "low"))],
        ["Validation (passed / warnings / failed)",
         f"{validation['summary']['passed']} / {validation['summary']['warnings']} / {validation['summary']['failed']}"],
    ]))

    # ---- departments ----
    add("\n## Departments discovered\n")
    rows = []
    for d in sorted(e.of_type("department"), key=lambda x: x.entity_id):
        heads = ", ".join(e.get("role", r).name for r in d.attributes.get("head_role_ids", []))
        procs = len(result.graph.neighbors(d.key, "owned_by", "in", current_only=True))
        rows.append([d.entity_id, d.name, heads, d.attributes.get("head_location_id"),
                     d.attributes.get("employees_in_employees_csv"), procs])
    add(_table(["ID", "Department", "Head", "Head location", "Employees", "Current processes/products owned"], rows))

    # ---- roles ----
    add("\n## Roles discovered\n")
    with_aliases = [r for r in result.roles if r.aliases]
    add(f"{len(result.roles)} roles, every one with documented responsibilities. "
        f"{sum(len(r.approval_rule_ids) > 0 for r in result.roles)} roles approve something; "
        f"{sum(len(r.escalation_rule_ids) > 0 for r in result.roles)} receive escalations. "
        "Documented aliases:\n")
    add(_table(["Role", "Also called", "Evidence"],
               [[r.name, ", ".join(r.aliases), _cut("; ".join(sum(e.get("role", r.role_id).attributes["alias_evidence"].values(), [])), 90)]
                for r in with_aliases]))

    # ---- employees ----
    add("\n## Employees discovered\n")
    by_loc = Counter(x.attributes.get("location_id") for x in e.of_type("employee"))
    add(_table(["Location", "Employees"], [[f"{e.get('location', loc).name} ({loc})", n] for loc, n in sorted(by_loc.items())]))
    ctx = result.employee_context
    add(f"\nAs of {summary.as_of}: {len(ctx['new_joiners'])} employees are within their first 90 days; "
        f"{len(ctx['joining_after_as_of'])} join later; {len(ctx['onboarding_in_progress_per_csv'])} have onboarding "
        f"'In Progress' in employees.csv.")

    # ---- processes ----
    add("\n## Processes discovered\n")
    rows = []
    for p in result.processes:
        rows.append([p.process_id, p.name, p.kind, p.status, ", ".join(o["name"] for o in p.owner_roles),
                     len(p.steps), len(p.approval_rule_ids), len(p.known_gaps)])
    add(_table(["ID", "Process", "Kind", "Status", "Owner", "Steps", "Approval rules", "Known gaps"], rows))

    # ---- products ----
    add("\n## Products discovered\n")
    rows = []
    for prod in sorted(e.of_type("product"), key=lambda x: x.entity_id):
        procs = [k.split(":", 1)[1] for k in result.graph.neighbors(prod.key, "uses", "in")]
        customers = [e.entities[k].name for k in result.graph.neighbors(prod.key, "used_by")]
        rows.append([prod.entity_id, prod.name, prod.attributes.get("category"), ", ".join(procs) or "-",
                     ", ".join(customers) or "-"])
    add(_table(["ID", "Product", "Category", "Used in process steps", "Named customers"], rows))

    # ---- topics ----
    add("\n## Topics discovered\n")
    rows = [[t.level, t.name, len(t.documents), ", ".join(t.keywords[:5])] for t in result.topics.topics]
    add(_table(["Level", "Topic", "Documents", "Top TF-IDF terms"], rows))
    unanchored = [th for th in result.topics.emergent["themes"] if th["unanchored"]]
    if unanchored:
        add(f"\nEmergent themes no anchored topic covers ({len(unanchored)}), from unsupervised clustering:\n")
        for th in unanchored:
            add(f"- {', '.join(th['top_terms'][:5])} ({', '.join(th['documents'])})")

    # ---- relationships ----
    add("\n## Relationships discovered\n")
    add(_table(["Relationship", "Count"], [[k, v] for k, v in sorted(summary.relationships_by_name.items(), key=lambda kv: -kv[1])]))
    add(f"\nDangling relationships: {summary.dangling_relationships}. Historical (archived) links kept: "
        f"{result.graph.summary()['historical_edges']}.")

    # ---- gaps ----
    add("\n## Knowledge gaps\n")
    gaps = result.gaps.to_dict()
    rows = [[g["severity"], g["gap_type"], _cut(g["description"])] for g in gaps["gaps"] if g["severity"] != "low"]
    add(_table(["Severity", "Type", "Description"], rows))
    low = Counter(g["gap_type"] for g in gaps["gaps"] if g["severity"] == "low")
    add("\nLow-severity gaps by type: " + ", ".join(f"{k} ({v})" for k, v in sorted(low.items())) + ".")
    clean = [c["check"] for c in gaps["checks"] if c["gaps_found"] == 0]
    add(f"\nChecks that found nothing missing: {', '.join(clean)}.")

    # ---- conflicts ----
    add("\n## Conflicts\n")
    add("KORA reports both sides and the metadata signals. It never decides which statement is correct.\n")
    rows = []
    for c in result.conflicts["conflicts"]:
        if c["conflict_type"] == "org_vs_employees":
            continue
        rows.append([c["conflict_id"], c["conflict_type"], _cut(c["topic"], 60), c["status"],
                     ", ".join(c["documents_involved"]), c["confidence"]])
    add(_table(["ID", "Type", "Topic", "Status", "Documents", "Confidence"], rows))
    low = [c for c in result.conflicts["conflicts"] if c["conflict_type"] == "org_vs_employees"]
    add(f"\nPlus {len(low)} low-confidence differences between employees.csv reporting lines and the org chart "
        "(labelled 'simplified', so possibly skip-level practice).")
    add(f"\nCorroborations: {len(result.conflicts['corroborations'])} cross-checks agreed "
        f"({', '.join(f'{k} {v}' for k, v in Counter(c['type'] for c in result.conflicts['corroborations']).items())}).")

    # ---- outdated ----
    add("\n## Outdated documents\n")
    rows = []
    for s in result.outdated["superseded_documents"]:
        for t in s["superseded_by"]:
            rows.append([s["document_id"], f"v{s['version']} ({s['effective_date']})",
                         f"{t['document_id']} v{t['version']} ({t['effective_date']})", len(t["evidence"]),
                         "unchanged" if (s["approver_changes"] or {}).get("unchanged") else "-"])
    add(_table(["Archived", "Version", "Replaced by", "Evidence pieces", "Approver"], rows))
    add(f"\nActive documents using legacy terminology: {len(result.outdated['legacy_terminology_in_active_documents'])}. "
        f"Stale references: {len(result.outdated['stale_references_in_active_documents'])}. "
        "History is kept, not deleted.")

    # ---- Germany ----
    add("\n## Germany employee-care knowledge\n")
    g = result.germany.to_dict(e)
    add(f"{len(g['items'])} checklist items from {', '.join(g['program']['documents'])} "
        f"(overview {g['program'].get('overview_document')}). Items deferring to official guidance: "
        f"{sum(1 for i in g['items'] if i['official_guidance_note'])}. Progress source: {g['progress_source']}.\n")
    add(_table(["Order", "Item", "Suggested by day", "Depends on", "Official guidance note", "Often forgotten"],
               [[n + 1, s["title"], s["due_by_day"] or "-",
                 ", ".join(d["item_id"] for d in result.germany.items[s["item_id"]].depends_on) or "-",
                 "yes" if s["official_guidance_note"] else "-",
                 result.germany.items[s["item_id"]].commonly_forgotten["rank"]
                 if result.germany.items[s["item_id"]].commonly_forgotten else "-"]
                for n, s in enumerate(g["general_steps"])]))
    add("\nEligible employees: " + ", ".join(f"{x['employee_id']} ({x['eligibility']['status']}"
                                              + (f", {x['eligibility']['stage']})" if x['eligibility']['status'] == 'active' else ")")
                                              for x in g["employees"]) + ".")

    # ---- communication ----
    add("\n## Communication and tone knowledge\n")
    c = result.communication.to_dict(e)
    add(f"Framework ({c['framework']['document_id']}): " +
        " → ".join(layer["layer"] for layer in c["framework"]["layers"]) + f". Rule: *{c['framework']['precedence']}*\n")
    add(_table(["Profile", "Offices", "Dimensions", "Suggested starting tone (hypothesis)"],
               [[p["profile_id"], ", ".join(p["location_ids"]) or "default", len(p["dimensions"]),
                 p["suggested_starting_tone"]["tone"]] for p in c["profiles"]]))
    add(f"\nHedged-language check on place-based profiles: {len(c['hedging_check']['unhedged_statements'])} "
        f"unhedged statements. Individual preferences known: {c['individual_preferences']['count']}.")

    # ---- validation ----
    add("\n## Validation\n")
    add(_table(["Check", "Status", "Count"], [[x["check"], x["status"].upper(), x["count"]] for x in validation["checks"]]))

    # ---- questions ----
    add("\n## Test questions\n")
    add(f"{sum(a['status'] == 'answered' for a in answers)} of {len(answers)} answered from the intelligence layer "
        "(see `test_questions.json` for items and sources).\n")
    add(_table(["#", "Category", "Question", "Answer"],
               [[a["id"], a["category"], a["question"], _cut(a.get("answer") or a.get("error"), 160)] for a in answers]))
    return "\n".join(out) + "\n"
